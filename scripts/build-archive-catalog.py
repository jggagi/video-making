#!/usr/bin/env python3
"""Index retained films for GitHub Releases without moving or re-encoding them."""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import re
import shutil
import subprocess
from urllib.parse import quote

REPOSITORY = "jggagi/video-making"
GENERATED_BY = "scripts/build-archive-catalog.py"
GENERATED_MARKER = "<!-- Generated by scripts/build-archive-catalog.py; edit source project notes instead. -->"
VIDEO_SUFFIXES = {".mp4", ".mov", ".webm"}
MEDIA_SUFFIXES = VIDEO_SUFFIXES | {".zip"}
HISTORICAL = (
    ("lanting", "兰亭集序", ["out", "out/museum", "out/extended", "out/time-bridge"], "."),
    ("madman", "狂人日记", ["out/madman"], "."),
    ("si-eternity", "一眼万年", ["si-eternity/out"], "si-eternity"),
    ("si-cage-7plus2", "7±2 的囚笼", ["si-cage-7plus2/out"], "si-cage-7plus2"),
    ("qstory-ep03", "余问 QStory EP.03：十万亿个分身", ["qstory-ep03/out"], "qstory-ep03"),
)
PREVIEW = re.compile(r"sample|preview|draft|opening-title|ending-title|样片|点睛片段", re.I)
DEFAULT_DURATION_SECONDS = 120
PCM_SAMPLE_RATE = 48_000
SUPPORTED_FPS = {24, 25, 30, 50, 60}
SUPPORTED_FINAL_DIMENSIONS = {
    "bilibili": {(3840, 2160)},
    "xiaohongshu": {(2160, 3840), (1080, 1920)},
}


def _inside(root: Path, path: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _release_tag(slug: str) -> str:
    ascii_slug = re.sub(r"[^A-Za-z0-9-]+", "-", slug).strip("-").lower()[:64] or "work"
    slug_hash = hashlib.sha256(slug.encode("utf-8")).hexdigest()[:12]
    return f"film-{ascii_slug}-{slug_hash}"


def _duration_fraction(value: object, manifest_path: Path) -> Fraction:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(
            f"duration_seconds must be a finite positive JSON number: {manifest_path}"
        )
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError(
            f"duration_seconds must be a finite positive JSON number: {manifest_path}"
        )
    try:
        duration = Fraction(str(value))
    except (ValueError, ZeroDivisionError):
        raise ValueError(
            f"duration_seconds must be a finite positive JSON number: {manifest_path}"
        ) from None
    if duration <= 0:
        raise ValueError(f"duration_seconds must be positive: {manifest_path}")
    sample_count = duration * PCM_SAMPLE_RATE
    if sample_count.denominator != 1:
        raise ValueError(
            f"duration_seconds times 48000 must be an integer PCM sample count: {manifest_path}"
        )
    return duration


def _duration_number(duration: Fraction) -> int | float:
    if duration.denominator == 1:
        return duration.numerator
    return float(duration)


def _format_seconds(value: int | float) -> str:
    return format(value, "g")


def _validate_manifest_slug(directory: Path, manifest: dict, manifest_path: Path) -> str:
    slug = manifest.get("slug")
    if (not isinstance(slug, str) or not slug or slug in {".", ".."}
            or "/" in slug or "\\" in slug or "\x00" in slug):
        raise ValueError(f"New delivery slug must be a nonempty one-component string: {manifest_path}")
    if slug != directory.name:
        raise ValueError(f"Delivery slug must exactly match its directory name: {manifest_path}")
    return slug


def _validate_final_outputs(
    root: Path, directory: Path, manifest: dict, manifest_path: Path
) -> tuple[dict[str, str], dict[str, tuple[int, int] | None]]:
    outputs = manifest.get("outputs")
    if not isinstance(outputs, dict):
        raise ValueError(f"New delivery must declare outputs.bilibili.path and outputs.xiaohongshu.path: {manifest_path}")

    resolved_root = root.resolve(strict=True)
    work_root = directory.resolve(strict=True)
    if not _inside(resolved_root, work_root):
        raise ValueError(f"New delivery directory escapes repository root: {directory}")
    final_output_paths: dict[str, str] = {}
    final_output_dimensions: dict[str, tuple[int, int] | None] = {}
    for key, platform in (("bilibili", "B站"), ("xiaohongshu", "小红书")):
        output = outputs.get(key)
        relative = output.get("path") if isinstance(output, dict) else None
        if not isinstance(relative, str) or not relative or "\\" in relative or "\x00" in relative:
            raise ValueError(f"New delivery must declare a relative {key} output path: {manifest_path}")
        has_width = "width" in output
        has_height = "height" in output
        if has_width != has_height:
            raise ValueError(
                f"Final {platform} dimensions must declare both width and height: {manifest_path}"
            )
        dimensions = None
        if has_width:
            width, height = output["width"], output["height"]
            if type(width) is not int or type(height) is not int:
                raise ValueError(
                    f"Final {platform} dimensions must be integer values: {manifest_path}"
                )
            dimensions = (width, height)
            if dimensions not in SUPPORTED_FINAL_DIMENSIONS[key]:
                raise ValueError(
                    f"Final {platform} dimensions are unsupported: {width}x{height}: {manifest_path}"
                )
        components = relative.split("/")
        if (len(components) != 2 or components[0] != platform
                or components[1] in {"", ".", ".."}):
            raise ValueError(f"Final {platform} output must be directly inside {platform}/: {relative}")
        if Path(components[1]).suffix.lower() not in VIDEO_SUFFIXES:
            raise ValueError(f"Final {platform} output must be a video file: {relative}")

        platform_directory = directory / platform
        output_path = directory.joinpath(*components)
        if platform_directory.is_symlink() or not platform_directory.is_dir():
            raise ValueError(f"Final output directory must be a real directory: {platform_directory}")
        if output_path.is_symlink() or not output_path.is_file():
            raise ValueError(f"Final {platform} output must be an existing regular nonsymlink file: {output_path}")
        resolved_output = output_path.resolve(strict=True)
        if not _inside(work_root, resolved_output):
            raise ValueError(f"Final {platform} output escapes its work directory: {relative}")
        if output_path.parent.resolve(strict=True) != platform_directory.resolve(strict=True):
            raise ValueError(f"Final {platform} output must be directly inside {platform}/: {relative}")
        final_output_paths[platform] = output_path.relative_to(root).as_posix()
        final_output_dimensions[platform] = dimensions
    return final_output_paths, final_output_dimensions


def _validate_unique_work_ids_and_tags(works: list[dict]) -> None:
    seen_ids: set[str] = set()
    seen_tags: set[str] = set()
    for work in works:
        if work["id"] in seen_ids:
            raise ValueError(f"Duplicate work id across archive: {work['id']}")
        if work["release_tag"] in seen_tags:
            raise ValueError(f"Duplicate Release tag across archive: {work['release_tag']}")
        seen_ids.add(work["id"])
        seen_tags.add(work["release_tag"])


def _validate_new_work_identities(works: list[dict]) -> None:
    historical_ids = {work_id for work_id, _, _, _ in HISTORICAL}
    historical_tags = {f"archive-{work_id}-v1" for work_id in historical_ids}
    new_works = [work for work in works if not work["historical"]]
    for work in new_works:
        if work["id"] in historical_ids:
            raise ValueError(f"New work id collides with a historical work: {work['id']}")
        if work["release_tag"] in historical_tags:
            raise ValueError(f"New Release tag collides with a historical tag: {work['release_tag']}")
    _validate_unique_work_ids_and_tags(works)


def _check_generated_markdown_target(path: Path) -> None:
    if not path.exists() and not path.is_symlink():
        return
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Refusing to overwrite non-regular generated Markdown path: {path}")
    with path.open("r", encoding="utf-8") as handle:
        first_line = handle.readline().rstrip("\r\n")
    if first_line != GENERATED_MARKER:
        raise ValueError(f"Refusing to overwrite unmarked Markdown; preserve its notes: {path}")


def _write_generated_markdown(path: Path, content: str) -> None:
    _check_generated_markdown_target(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{GENERATED_MARKER}\n\n{content.strip()}\n", encoding="utf-8")


def _generated_markdown_targets(root: Path, works: list[dict]) -> list[Path]:
    targets = [root / "deliveries" / "README.md"]
    for work in works:
        delivery = root / work["delivery_directory"]
        targets.extend((delivery / "README.md", delivery / "B站" / "README.md", delivery / "小红书" / "README.md"))
    return targets


def file_hash(path: Path) -> str:
    before = path.stat()
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for data in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            digest.update(data)
    after = path.stat()
    if (before.st_size, before.st_mtime_ns, before.st_ino) != (after.st_size, after.st_mtime_ns, after.st_ino):
        raise ValueError(f"File changed during hashing: {path}")
    return digest.hexdigest()


def probe(path: Path) -> dict:
    result = subprocess.run(
        ["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", str(path)],
        capture_output=True, text=True, check=True,
    )
    data = json.loads(result.stdout)
    video = next(stream for stream in data["streams"] if stream.get("codec_type") == "video")
    return {
        "width": video["width"], "height": video["height"],
        "fps": video["avg_frame_rate"], "frames": video.get("nb_frames"),
        "video_duration_seconds": float(video["duration"]),
        "container_duration_seconds": float(data["format"]["duration"]),
    }


def discover(root: Path) -> list[dict]:
    works = []
    for work_id, title, directories, project in HISTORICAL:
        files = sorted({path for directory in directories for path in (root / directory).glob("*")
                        if path.is_file() and path.suffix.lower() in {".mp4", ".mov", ".webm", ".zip"}})
        if files:
            works.append({"id": work_id, "title": title, "files": files,
                          "release_tag": f"archive-{work_id}-v1", "historical": True,
                          "project_path": project, "delivery_directory": f"deliveries/legacy-{work_id}"})
    deliveries = root / "deliveries"
    if deliveries.exists():
        for directory in sorted(deliveries.iterdir()):
            manifest_path = directory / "delivery.json"
            if not directory.is_dir() or not manifest_path.is_file():
                continue
            if directory.is_symlink():
                raise ValueError(f"New delivery directory must not be a symlink: {directory}")
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            if manifest.get("schema_version") != 1:
                raise ValueError(f"New delivery must use schema1: {manifest_path}")
            duration_value = manifest.get("duration_seconds", DEFAULT_DURATION_SECONDS)
            duration = _duration_fraction(duration_value, manifest_path)
            slug = _validate_manifest_slug(directory, manifest, manifest_path)
            final_output_paths, final_output_dimensions = _validate_final_outputs(
                root, directory, manifest, manifest_path
            )
            files = sorted(path for path in directory.rglob("*") if path.is_file()
                           and path.suffix.lower() in MEDIA_SUFFIXES
                           and not any(part.startswith("bundle") or part == "node_modules"
                                       for part in path.relative_to(directory).parts[:-1]))
            works.append({"id": slug, "title": manifest["title"], "files": files,
                          "release_tag": _release_tag(slug), "historical": False,
                          "duration_seconds": _duration_number(duration),
                          "project_path": (directory / "project").relative_to(root).as_posix(),
                          "delivery_directory": directory.relative_to(root).as_posix(),
                          "final_output_paths": final_output_paths,
                          "final_output_dimensions": final_output_dimensions})
    _validate_new_work_identities(works)
    return works


def make_asset(root: Path, work: dict, path: Path) -> dict:
    if path.is_symlink():
        raise ValueError(f"Media symlinks must be resolved explicitly: {path}")
    relative = path.relative_to(root).as_posix()
    digest = file_hash(path)
    stem = re.sub(r"[^A-Za-z0-9._-]+", "-", str(Path(relative).with_suffix("")).replace("/", "--")).strip(".-")
    prefix = re.sub(r"[^A-Za-z0-9._-]+", "-", work["id"]).strip(".-") or "film"
    name = prefix + "--" + stem + "--" + digest[:12] + path.suffix.lower()
    if len(name.encode("utf-8")) > 255:
        raise ValueError(f"Release asset name too long: {relative}")
    size = path.stat().st_size
    if not 0 < size < 2 * 1024**3:
        raise ValueError(f"Release asset must be nonempty and under2GiB: {relative}")
    kind = "project" if path.suffix.lower() == ".zip" else "video"
    measurements = {} if kind == "project" else probe(path)
    if kind == "project":
        platform = "工程"
    elif work["historical"]:
        if PREVIEW.search(path.name):
            platform = "预览"
        else:
            platform = "小红书" if measurements["height"] > measurements["width"] else "B站"
    else:
        relative_project_path = work["project_path"].rstrip("/")
        if relative == relative_project_path or relative.startswith(relative_project_path + "/"):
            platform = "工程"
        elif relative in work["final_output_paths"].values():
            platform = next(name for name, output_path in work["final_output_paths"].items()
                            if output_path == relative)
        else:
            platform = "预览"
    if not work["historical"] and kind == "video" and relative in work["final_output_paths"].values():
        final_platform = next(name for name, output_path in work["final_output_paths"].items()
                              if output_path == relative)
        declared_size = work["final_output_dimensions"][final_platform]
        supported_sizes = ({declared_size} if declared_size is not None else
                           SUPPORTED_FINAL_DIMENSIONS["bilibili" if final_platform == "B站"
                                                      else "xiaohongshu"])
        if (measurements["width"], measurements["height"]) not in supported_sizes:
            raise ValueError(f"New platform output has wrong dimensions: {relative}")
        try:
            fps = Fraction(measurements["fps"])
        except (KeyError, ValueError, ZeroDivisionError):
            raise ValueError(f"New platform output has an invalid frame rate: {relative}") from None
        duration = Fraction(str(work["duration_seconds"]))
        frame_count = duration * fps
        if (fps.denominator != 1 or fps.numerator not in SUPPORTED_FPS
                or frame_count.denominator != 1
                or measurements["frames"] != str(frame_count.numerator)):
            raise ValueError(f"New platform output must contain exactly {work['duration_seconds']} seconds of frames: {relative}")
        if abs(measurements["video_duration_seconds"] - float(duration)) > 1 / float(fps):
            raise ValueError(f"New platform output duration must be within one frame of {work['duration_seconds']} seconds: {relative}")
    return {"path": relative, "name": name, "bytes": size, "sha256": digest,
            "kind": kind, "platform": platform, "measurements": measurements,
            "download_url": f"https://github.com/{REPOSITORY}/releases/download/{quote(work['release_tag'], safe='')}/{quote(name, safe='')}"}


def table(assets: list[dict]) -> str:
    rows = ["| 文件 | 规格 | 大小 |", "| --- | --- | --- |"]
    for asset in assets:
        measured = asset["measurements"]
        spec = (f"{measured['width']}×{measured['height']}，{measured['video_duration_seconds']:.3f}秒"
                if measured else "可编辑工程 / 历史快照")
        rows.append(f"| [{Path(asset['path']).name}]({asset['download_url']}) | {spec} | {asset['bytes'] / 1024**2:.1f} MiB |")
    return "\n".join(rows) + "\n"


def write_work(root: Path, work: dict, assets: list[dict]) -> None:
    delivery = root / work["delivery_directory"]
    delivery.mkdir(parents=True, exist_ok=True)
    release = f"https://github.com/{REPOSITORY}/releases/tag/{quote(work['release_tag'], safe='')}"
    historical = ("这是历史归档，保留原时长、画幅与版本；不声称符合后续新作品的时长规格。\n"
                  if work["historical"] else
                  f"两版制作目标均为{_format_seconds(work['duration_seconds'])}秒，验收状态见本作品 review/。\n")
    text = f"# {work['title']}\n\n{historical}\n"
    text += f"[完整 Release 与全部下载]({release}) · [B站横屏](B站/README.md) · [小红书竖屏](小红书/README.md)\n\n"
    text += f"源码位置：`{work['project_path']}`。成片在 GitHub Releases；本机原始路径、SHA-256、实测规格见 [archive.json](archive.json)。\n\n"
    projects = [asset for asset in assets if asset["platform"] == "工程"]
    if projects:
        text += "## 工程归档\n\n" + table(projects) + "\n"
    previews = [asset for asset in assets if asset["platform"] == "预览"]
    if previews:
        text += "## 样片与历史草稿\n\n这些文件仅作制作过程记录，不能视为最终成片。\n\n" + table(previews)
    _write_generated_markdown(delivery / "README.md", text)
    for platform in ("B站", "小红书"):
        folder = delivery / platform
        folder.mkdir(exist_ok=True)
        selected = [asset for asset in assets if asset["platform"] == platform]
        text = f"# {work['title']} · {platform}\n\n"
        text += "按画幅分类归档，不表示已经发布到平台账号。\n\n"
        text += table(selected) if selected else "当前未发现此画幅的成片；未为归档补做或裁切视频。\n"
        _write_generated_markdown(folder / "README.md", text)
    record = {key: value for key, value in work.items() if key != "files"}
    record["assets"] = assets
    record["generated_by"] = GENERATED_BY
    (delivery / "archive.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # Copy only compact historical evidence/subtitles; never move the originals.
    if work["historical"]:
        for directory in sorted({path.parent for path in work["files"]}):
            for path in sorted(directory.glob("*")):
                if not path.is_file() or path.is_symlink():
                    continue
                suffix = path.suffix.lower()
                if suffix in {".srt", ".vtt"}:
                    platform = "小红书" if re.search(r"xhs|portrait", path.name, re.I) else "B站"
                    name = path.relative_to(root).as_posix().replace("/", "--")
                    target = delivery / platform / name
                elif suffix in {".json", ".txt"} and path.stat().st_size < 512 * 1024:
                    folder = delivery / "review"
                    folder.mkdir(exist_ok=True)
                    target = folder / path.relative_to(root).as_posix().replace("/", "--")
                else:
                    continue
                if target.exists() and target.read_bytes() != path.read_bytes():
                    raise ValueError(f"Existing archive evidence differs; preserve it and use a new version: {target}")
                if not target.exists():
                    shutil.copyfile(path, target)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    works = discover(root)
    catalog = {"schema_version": 1, "repository": REPOSITORY,
               "generated_by": GENERATED_BY, "works": []}
    # Inspect/hash every source before emitting catalog/index changes.
    prepared = [(work, [make_asset(root, work, path) for path in work["files"]]) for work in works]
    for path in _generated_markdown_targets(root, works):
        _check_generated_markdown_target(path)
    for work, assets in prepared:
        write_work(root, work, assets)
        record = {key: value for key, value in work.items() if key != "files"}
        record["assets"] = assets
        catalog["works"].append(record)
    directory = root / "archive"
    directory.mkdir(exist_ok=True)
    (directory / "catalog.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    total = sum(asset["bytes"] for _, assets in prepared for asset in assets)
    count = sum(len(assets) for _, assets in prepared)
    index = "# 全部作品索引\n\n每部作品独立目录，按 B站/小红书画幅提供下载索引。成片和工程 ZIP 位于本仓库 Releases。\n\n"
    for work, assets in prepared:
        relative = Path(work["delivery_directory"]).relative_to("deliveries").as_posix()
        index += f"- [{work['title']}]({quote(relative, safe='/')}/README.md)：{len(assets)} 个视频/工程资产。\n"
    _write_generated_markdown(root / "deliveries" / "README.md", index)
    print(f"Indexed {len(works)} works, {count} media/project assets, {total:,} bytes; originals unchanged")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, StopIteration, subprocess.CalledProcessError) as error:
        raise SystemExit(f"Archive indexing stopped: {error}") from None
