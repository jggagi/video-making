#!/usr/bin/env python3
"""Safely build a local library of released final videos using APFS clones."""

from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import os
import re
import stat
import sys
import tempfile
from pathlib import Path
from urllib.parse import quote

GENERATED_BY = "scripts/build-final-library.py"
README_MARKER = "<!-- Generated by scripts/build-final-library.py; edit source project notes instead. -->"
PLATFORMS = {"B站", "小红书"}
VIDEO_SUFFIXES = {".mp4", ".mov", ".webm"}
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
WORK_DIRS = {
    "lanting": "兰亭集序",
    "madman": "狂人日记",
    "si-eternity": "一眼万年",
    "si-cage-7plus2": "7±2的囚笼",
    "qstory-ep03": "EP03-十万亿个分身-v01",
    "si-ep03-million-mind-v02": "EP03-百万分身-v02",
}


class LibraryError(RuntimeError):
    pass


def signature(info):
    return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def check_path(root: Path, rel: Path, allow_missing=False) -> Path:
    if rel.is_absolute() or ".." in rel.parts:
        raise LibraryError(f"Path must stay inside repository: {rel}")
    path = root
    for i, part in enumerate(rel.parts):
        path = path / part
        try:
            info = path.lstat()
        except FileNotFoundError:
            if allow_missing:
                return root / rel
            raise LibraryError(f"Missing path: {path}") from None
        if stat.S_ISLNK(info.st_mode):
            raise LibraryError(f"Refusing symlink: {path}")
        if i < len(rel.parts) - 1 and not stat.S_ISDIR(info.st_mode):
            raise LibraryError(f"Path ancestor is not a directory: {path}")
    return root / rel


def regular_file(path: Path, label: str):
    info = path.lstat()
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        raise LibraryError(f"Expected regular nonsymlink {label}: {path}")
    return info


def stable_sha(path: Path, expected=None):
    before = regular_file(path, "file")
    before_sig = signature(before)
    if expected is not None and before_sig != expected:
        raise LibraryError(f"File changed since preflight: {path}")
    fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    try:
        if signature(os.fstat(fd)) != before_sig:
            raise LibraryError(f"File changed while opening: {path}")
        digest = hashlib.sha256()
        with os.fdopen(fd, "rb", closefd=False) as source:
            for block in iter(lambda: source.read(4 * 1024 * 1024), b""):
                digest.update(block)
        if signature(os.fstat(fd)) != before_sig or signature(path.lstat()) != before_sig:
            raise LibraryError(f"File changed while hashing: {path}")
        return digest.hexdigest()
    finally:
        os.close(fd)


def rel_path(value, label):
    if not isinstance(value, str) or not value or "\x00" in value or "\\" in value:
        raise LibraryError(f"Invalid {label} path: {value!r}")
    path = Path(value)
    if path.is_absolute() or ".." in path.parts:
        raise LibraryError(f"Unsafe {label} path: {value}")
    return path


def metadata_preflight(final_root: Path):
    if final_root.exists() or final_root.is_symlink():
        info = final_root.lstat()
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            raise LibraryError(f"Refusing unsafe final directory: {final_root}")
    index, readme = final_root / "index.json", final_root / "README.md"
    for path in (index, readme):
        if not path.exists() and not path.is_symlink():
            continue
        if path.is_symlink() or not path.is_file():
            raise LibraryError(f"Refusing unsafe metadata path: {path}")
    if index.exists():
        try:
            data = json.loads(index.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise LibraryError(f"Cannot verify existing index: {exc}") from exc
        if not isinstance(data, dict) or data.get("generated_by") != GENERATED_BY:
            raise LibraryError(f"Refusing to replace unrecognized metadata: {index}")
    if readme.exists():
        with readme.open(encoding="utf-8") as source:
            if source.readline().rstrip("\r\n") != README_MARKER:
                raise LibraryError(f"Refusing to replace unrecognized metadata: {readme}")
    return index, readme


def load_entries(root: Path, catalog_arg: str | None):
    catalog_rel = Path(catalog_arg) if catalog_arg else Path("archive/catalog.json")
    if catalog_rel.is_absolute():
        try:
            catalog_rel = catalog_rel.relative_to(root)
        except ValueError:
            raise LibraryError("--catalog must stay inside --root") from None
    catalog_path = check_path(root, catalog_rel)
    regular_file(catalog_path, "catalog")
    try:
        catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise LibraryError(f"Cannot read archive catalog: {exc}") from exc
    if not isinstance(catalog, dict) or catalog.get("schema_version") != 1 or not isinstance(catalog.get("works"), list):
        raise LibraryError("Unsupported archive catalog schema; expected schema_version 1 with works[]")

    entries, targets = [], set()
    for work in catalog["works"]:
        if not isinstance(work, dict) or not isinstance(work.get("assets"), list):
            raise LibraryError("Invalid work/assets structure in archive catalog")
        work_id, title = work.get("id"), work.get("title")
        if not isinstance(work_id, str) or not work_id or not isinstance(title, str) or not title:
            raise LibraryError("Archive catalog work is missing id/title")
        for asset in work["assets"]:
            if not isinstance(asset, dict):
                raise LibraryError(f"Invalid asset in work {work_id}")
            if asset.get("kind") != "video" or asset.get("platform") not in PLATFORMS:
                continue
            source_rel = rel_path(asset.get("path"), "source")
            if source_rel.suffix.lower() not in VIDEO_SUFFIXES:
                raise LibraryError(f"Selected video has an unsupported extension: {source_rel}")
            size, digest, url = asset.get("bytes"), asset.get("sha256"), asset.get("download_url")
            if type(size) is not int or size <= 0 or not isinstance(digest, str) or not SHA256_RE.fullmatch(digest):
                raise LibraryError(f"Selected video has invalid size or SHA-256: {source_rel}")
            if not isinstance(url, str) or not url.startswith("https://"):
                raise LibraryError(f"Selected video has invalid download URL: {source_rel}")
            source = check_path(root, source_rel)
            src_stat = regular_file(source, "video source")
            if src_stat.st_size != size:
                raise LibraryError(f"Catalog/source size mismatch: {source_rel}")
            work_dir = WORK_DIRS.get(work_id, work_id)
            if Path(work_dir).is_absolute() or len(Path(work_dir).parts) != 1 or work_dir in {".", ".."}:
                raise LibraryError(f"Unsafe work directory for id {work_id!r}")
            final_rel = Path("final") / work_dir / asset["platform"] / source_rel.name
            if final_rel.as_posix() in targets:
                raise LibraryError(f"Duplicate final destination: {final_rel}")
            targets.add(final_rel.as_posix())
            target = check_path(root, final_rel, allow_missing=True)
            if target.exists() or target.is_symlink():
                regular_file(target, "existing destination")
            entries.append({
                "work_id": work_id, "title": title, "work_dir": work_dir,
                "platform": asset["platform"], "source_path": source_rel.as_posix(),
                "source": source, "source_sig": signature(src_stat),
                "final_path": final_rel.as_posix(), "target": target,
                "bytes": size, "sha256": digest, "download_url": url,
            })
    if not entries:
        raise LibraryError("No B站/小红书 video assets found in archive catalog")
    entries.sort(key=lambda e: (e["work_id"], e["platform"], e["source_path"]))
    return entries


def verify_targets(entries):
    additions = skips = 0
    for e in entries:
        target = e["target"]
        if not target.exists() and not target.is_symlink():
            additions += 1
            continue
        target_stat = regular_file(target, "existing destination")
        source_stat = regular_file(e["source"], "source")
        if (target_stat.st_dev, target_stat.st_ino) == (source_stat.st_dev, source_stat.st_ino):
            raise LibraryError(f"Destination is hard-linked to source: {target}")
        if target_stat.st_size != e["bytes"] or stable_sha(target, signature(target_stat)) != e["sha256"]:
            raise LibraryError(f"Divergent destination; refusing to overwrite: {target}")
        e["skip"] = True
        e["target_sig"] = signature(target_stat)
        skips += 1
    return additions, skips


def clonefile_function():
    try:
        fn = ctypes.CDLL(None, use_errno=True).clonefile
    except (OSError, AttributeError) as exc:
        raise LibraryError(f"macOS libc clonefile is unavailable: {exc}") from exc
    fn.argtypes, fn.restype = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_int], ctypes.c_int
    return fn


def make_clone(clonefile, e):
    final, source = e["target"], e["source"]
    parent = final.parent
    missing = []
    cursor = parent
    while not cursor.exists():
        missing.append(cursor)
        cursor = cursor.parent
    for directory in reversed(missing):
        directory.mkdir()
    for directory in reversed(missing[:-1]):
        if directory.is_symlink() or not directory.is_dir():
            raise LibraryError(f"Unsafe destination directory: {directory}")
    src_now = regular_file(source, "source")
    if signature(src_now) != e["source_sig"]:
        raise LibraryError(f"Source changed before clone: {e['source_path']}")
    temp_dir = Path(tempfile.mkdtemp(prefix=".final-library-", dir=parent))
    temp = temp_dir / "video"
    try:
        if clonefile(os.fsencode(source), os.fsencode(temp), 0) != 0:
            err = ctypes.get_errno()
            raise LibraryError(f"clonefile failed; APFS is required and full-copy fallback is disabled: {source}: {os.strerror(err)}")
        clone_stat = regular_file(temp, "clone")
        if signature(source.lstat()) != e["source_sig"]:
            raise LibraryError(f"Source changed during clone: {e['source_path']}")
        if (clone_stat.st_dev, clone_stat.st_ino) == (e["source_sig"][0], e["source_sig"][1]):
            raise LibraryError(f"clonefile did not create an independent inode: {e['source_path']}")
        if clone_stat.st_size != e["bytes"] or stable_sha(temp, signature(clone_stat)) != e["sha256"]:
            raise LibraryError(f"Clone SHA/size verification failed: {e['source_path']}")
        try:
            os.link(temp, final, follow_symlinks=False)
        except FileExistsError:
            raise LibraryError(f"Destination appeared during publish; refusing overwrite: {final}") from None
        published = regular_file(final, "published destination")
        if (published.st_dev, published.st_ino) != (clone_stat.st_dev, clone_stat.st_ino):
            raise LibraryError(f"Published file differs from verified clone: {final}")
    finally:
        temp.unlink(missing_ok=True)
        temp_dir.rmdir()


def write_generated(path: Path, content: str, is_json: bool):
    # Callers preflight both metadata files before copying any video; recheck
    # the marker just before replacement to protect hand-written files.
    if path.exists():
        if path.is_symlink() or not path.is_file():
            raise LibraryError(f"Refusing unsafe metadata path: {path}")
        if is_json:
            data = json.loads(path.read_text(encoding="utf-8"))
            valid = isinstance(data, dict) and data.get("generated_by") == GENERATED_BY
        else:
            with path.open(encoding="utf-8") as source:
                valid = source.readline().rstrip("\r\n") == README_MARKER
        if not valid:
            raise LibraryError(f"Refusing to replace unrecognized metadata: {path}")
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    temp = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as out:
            out.write(content)
            out.flush()
            os.fsync(out.fileno())
        if path.exists():
            os.replace(temp, path)
        else:
            try:
                os.link(temp, path, follow_symlinks=False)
            except FileExistsError:
                raise LibraryError(f"Metadata appeared during write; refusing overwrite: {path}") from None
            temp.unlink()
    finally:
        temp.unlink(missing_ok=True)


def build_index(entries):
    return {
        "schema_version": 1,
        "generated_by": GENERATED_BY,
        "total_files": len(entries),
        "logical_bytes": sum(e["bytes"] for e in entries),
        "files": [{
            "source_path": e["source_path"], "final_path": e["final_path"],
            "work_id": e["work_id"], "title": e["title"], "platform": e["platform"],
            "bytes": e["bytes"], "sha256": e["sha256"], "download_url": e["download_url"],
            "materialization": "APFS clonefile for new files; existing independent matches are retained",
            "verification": "SHA-256 matches archive catalog; stable stat and inode checks passed",
        } for e in entries],
    }


def build_readme(entries):
    groups = {}
    for e in entries:
        groups.setdefault((e["work_id"], e["work_dir"], e["title"]), []).append(e)
    lines = [
        README_MARKER, "", "# Final 成片库", "",
        "本目录收录 archive catalog 中的正式 B站与小红书成片。历史正式版本与原始源路径均保留；样片和工程 ZIP 未纳入。",
        "", "每部影片提供本地相对文件链接和原始 GitHub Release 下载链接。新文件由 macOS APFS `clonefile` 创建为独立文件，共享未修改的数据块；APFS 克隆不是备份。影片不提交到 Git。",
    ]
    for (work_id, work_dir, title), files in groups.items():
        lines.extend(("", f"## {title} (`{work_id}`)", ""))
        for e in files:
            name = Path(e["final_path"]).name
            href = quote(f"{work_dir}/{e['platform']}/{name}", safe="/-._~")
            lines.append(f"- [{e['platform']} · {name}]({href}) · [GitHub 下载]({e['download_url']})")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent), help="repository root")
    parser.add_argument("--catalog", help="catalog path inside root (default: archive/catalog.json)")
    parser.add_argument("--dry-run", action="store_true", help="show a read-only plan")
    args = parser.parse_args()
    if sys.platform != "darwin":
        print("Unsupported platform: this operation requires macOS APFS clonefile; no files changed.", file=sys.stderr)
        return 2
    try:
        root = Path(args.root).resolve(strict=True)
        if not root.is_dir():
            raise LibraryError(f"Repository root is not a directory: {root}")
        entries = load_entries(root, args.catalog)
        index_path, readme_path = metadata_preflight(root / "final")
        additions, skips = verify_targets(entries)
        total_bytes = sum(e["bytes"] for e in entries)
        if args.dry_run:
            print(f"DRY RUN: total={len(entries)} logical_bytes={total_bytes} additions={additions} skips={skips}")
            for e in entries:
                action = "skip" if e.get("skip") else "add"
                print(f"[{action}] {e['work_id']} / {e['platform']}: {e['source_path']} -> {e['final_path']} ({e['bytes']} bytes)")
            return 0

        # Hash and stat-check all sources before the first clone to fail early
        # on catalog drift. No destination is created until this pass succeeds.
        for e in entries:
            if stable_sha(e["source"], e["source_sig"]) != e["sha256"]:
                raise LibraryError(f"Catalog/source SHA-256 mismatch: {e['source_path']}")
        clonefile = clonefile_function()
        created = 0
        skipped = 0
        for e in entries:
            if e.get("skip"):
                if stable_sha(e["target"], e["target_sig"]) != e["sha256"]:
                    raise LibraryError(f"Existing destination changed after verification: {e['target']}")
                skipped += 1
            else:
                make_clone(clonefile, e)
                created += 1

        final_root = root / "final"
        final_root.mkdir(exist_ok=True)
        index = build_index(entries)
        write_generated(index_path, json.dumps(index, ensure_ascii=False, indent=2) + "\n", True)
        write_generated(readme_path, build_readme(entries), False)
        print(f"COMPLETE: total={len(entries)} logical_bytes={total_bytes} created={created} skipped={skipped}")
        return 0
    except (LibraryError, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
